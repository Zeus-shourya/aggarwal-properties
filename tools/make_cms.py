"""Write .pages.yml (the Pages CMS form) from the map data and project names.

Run from the site folder after the plot maps or project names change:

    python tools/make_cms.py

The form has two pick-lists of plots per project, saved to data/status.json:
"p1" = sold (red) and "p1_resale" = available for resale (yellow).
"""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
maps = json.loads(re.search(r"window\.AP_MAPS = (\{.*\});", (root / "assets/js/plots-data.js").read_text("utf-8"), re.S).group(1))
proj_js = (root / "data/projects.js").read_text("utf-8")
names = dict(re.findall(r'key:\s*"(\w+)",\s*name:\s*"([^"]+)"', proj_js))
types = dict(re.findall(r'key:\s*"(\w+)",\s*name:\s*"[^"]+",\s*type:\s*"([^"]+)"', proj_js))


def q(s):
    return json.dumps(str(s), ensure_ascii=False)  # a JSON string is also a valid YAML string


out = [
    "# Pages CMS configuration - https://pagescms.org/docs/configuration/",
    "# GENERATED by tools/make_cms.py - re-run it instead of editing the plot lists by hand.",
    "#",
    "# This is the form the client sees in the editor (app.pagescms.org). Saving it commits",
    "# data/status.json to this repo; GitHub Pages then republishes the site (about a minute).",
    "",
    "# Photos uploaded in the editor are stored here. No leading slash on output: the site",
    "# lives in a sub-folder on github.io, so paths must stay relative.",
    "media:",
    "  input: assets/uploads",
    "  output: assets/uploads",
    "  rename: safe",
    "  categories: [image]",
    "",
    "content:",
    "  - name: sold",
    '    label: "Sold & resale plots"',
    "    type: file",
    "    path: data/status.json",
    "    format: json",
    "    fields:",
]
for key, m in maps.items():
    name = names.get(key, key)
    kind = types.get(key, "plots")
    lists = [
        (key, name + " - SOLD plots (red)",
         f"Pick every plot that is SOLD in {name} ({kind}). Sold plots turn red on the website; "
         "plots in neither list stay green. Remove a plot from this list to make it available again."),
        (key + "_resale", name + " - plots available for RESALE (yellow)",
         f"Pick every plot in {name} that its owner is offering for RESALE. These turn yellow on the "
         "website. A plot picked in both lists shows as yellow."),
    ]
    for field, label, desc in lists:
        out += [
            f"      - name: {field}",
            f"        label: {q(label)}",
            "        type: select",
            f"        description: {q(desc)}",
            "        options:",
            "          multiple: true",
            f"          placeholder: {q('Type a plot number...')}",
            "          values:",
        ]
        for p in m["plots"]:
            out.append(f"            - {{ name: {q(p['id'])}, label: {q('Plot ' + p['n'] + '  (' + format(p['a'], 'g') + ' sq yd)')} }}")

# The "Properties with us" tab on the Projects page: one list, saved as an array in
# data/properties.json. Each entry is one property card.
out += """
  - name: properties
    label: "Properties with us"
    type: file
    path: data/properties.json
    format: json
    list: true
    fields:
      - name: title
        label: Property title
        type: string
        required: true
        description: "e.g. 200 sq yd corner plot, Sector 14 / 3 BHK house / Shop on main road"
      - name: type
        label: Property type
        type: select
        options:
          values: [Plot, House / Kothi, Flat / Apartment, Shop / Showroom, Office / Commercial, Industrial, Agricultural land, Other]
      - name: purpose
        label: For
        type: select
        options:
          values: [For sale, For rent]
      - name: status
        label: Status
        type: select
        required: true
        default: available
        description: "Sold properties stay on the website with a red Sold badge. Hidden removes it from the website without deleting it."
        options:
          values:
            - { name: available, label: Available }
            - { name: sold, label: Sold }
            - { name: hidden, label: Hidden (not shown on website) }
      - name: location
        label: Location / locality
        type: string
      - name: size
        label: Size
        type: string
        description: "Write it as you want it shown, e.g. 200 sq yd / 3 BHK, 150 sq yd / 2 acres"
      - name: price
        label: Price
        type: string
        description: "Write it as you want it shown, e.g. Rs 45 Lakh or Rs 25,000 / month. Leave empty to show On request."
      - name: facing
        label: Facing (optional)
        type: select
        options:
          values: [East, West, North, South, North-East, North-West, South-East, South-West]
      - name: description
        label: Short description
        type: text
      - name: photos
        label: Photos
        type: image
        description: "First photo is the cover. Phone photos are fine."
        options:
          multiple:
            max: 12
          extensions: [jpg, jpeg, png, webp]
""".strip("\n").split("\n")
(root / ".pages.yml").write_text("\n".join(out) + "\n", "utf-8")
print("wrote .pages.yml:", {k: len(m["plots"]) for k, m in maps.items()}, names)
