"""Write .pages.yml (the Pages CMS form) from the map data and project names.

Run from the site folder after the plot maps or project names change:

    python tools/make_cms.py

The form has one tick-list of plots per project; whatever is ticked is saved
to data/status.json as SOLD.
"""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
maps = json.loads(re.search(r"window\.AP_MAPS = (\{.*\});", (root / "assets/js/plots-data.js").read_text("utf-8"), re.S).group(1))
proj_js = (root / "data/projects.js").read_text("utf-8")
names = dict(re.findall(r'key:\s*"(\w+)",\s*name:\s*"([^"]+)"', proj_js))
types = dict(re.findall(r'key:\s*"(\w+)",\s*name:\s*"[^"]+",\s*type:\s*"([^"]+)"', proj_js))


def q(s):
    return json.dumps(str(s), ensure_ascii=False)  # a JSON string is also a valid YAML string


out = [
    "# Pages CMS configuration - https://pagescms.org/docs/configuration/",
    "# GENERATED by tools/make_cms.py - re-run it instead of editing the plot lists by hand.",
    "#",
    "# This is the form the client sees in the editor (app.pagescms.org). Saving it commits",
    "# data/status.json to this repo; GitHub Pages then republishes the site (about a minute).",
    "",
    "content:",
    "  - name: sold",
    "    label: Sold plots",
    "    type: file",
    "    path: data/status.json",
    "    format: json",
    "    fields:",
]
for key, m in maps.items():
    name = names.get(key, key)
    out += [
        f"      - name: {key}",
        f"        label: {q(name + ' - SOLD plots')}",
        "        type: select",
        f"        description: {q('Pick every plot that is SOLD in ' + name + ' (' + types.get(key, 'plots') + '). Sold plots turn red on the website; all other plots stay green. Remove a plot from this list to make it available again.')}",
        "        options:",
        "          multiple: true",
        f"          placeholder: {q('Type a plot number...')}",
        "          values:",
    ]
    for p in m["plots"]:
        out.append(f"            - {{ name: {q(p['id'])}, label: {q('Plot ' + p['n'] + '  (' + format(p['a'], 'g') + ' sq yd)')} }}")
(root / ".pages.yml").write_text("\n".join(out) + "\n", "utf-8")
print("wrote .pages.yml:", {k: len(m["plots"]) for k, m in maps.items()}, names)
